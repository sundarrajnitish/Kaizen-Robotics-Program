"""Bundle the existing simulation documents for the offline single-page lab.
Run after changing a demo HTML file or experiments.json.
"""
from pathlib import Path
import json
root = Path(__file__).resolve().parents[1]
items = json.loads((root / 'demos/experiments.json').read_text())
documents = {item['url'].split('?')[0]: (root / 'demos' / item['url'].split('?')[0]).read_text() for item in items}
(root / 'demos/assets/experiments.js').write_text('// Generated by tools/build-demos.py\nwindow.EXPERIMENTS = ' + json.dumps(items) + ';\nwindow.EXPERIMENT_DOCUMENTS = ' + json.dumps(documents) + ';\n')
